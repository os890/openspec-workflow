#!/usr/bin/env node
// An app launcher for the OpenSpec dashboard: one click starts the dashboard (if it is not running yet) and opens it
// in the browser. macOS: an app in ~/Applications (Launchpad, Spotlight, Dock); Linux: a desktop entry.
//
//   node launcher.mjs install [--name="OpenSpec Dashboard"] [--port=4590] [--app-window] -- <server options>
//   node launcher.mjs uninstall [--name="OpenSpec Dashboard"]
//   node launcher.mjs stop [--port=4590]          stops a dashboard the launcher started
//
// Everything after "--" is passed to server.mjs, e.g. `-- --agent --scan=~/code` or `-- --agent --project=~/code/app`.
// The launcher remembers the folder it was installed from (relative paths in the options start there), this Node.js
// and the PATH, since an app started from the Dock gets neither a shell nor its PATH. --app-window opens the
// dashboard in a window of its own (Chrome, Edge or Brave in app mode) instead of a browser tab.
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const STATE_DIR = path.join(process.env.XDG_STATE_HOME || path.join(os.homedir(), '.local', 'state'), 'openspec-dashboard');
const argv = process.argv.slice(2);
const cut = argv.indexOf('--');
const own = cut < 0 ? argv : argv.slice(0, cut), serverArgs = cut < 0 ? [] : argv.slice(cut + 1);
const cmd = own[0];
const opt = (k, d) => { const a = own.find((x) => x === `--${k}` || x.startsWith(`--${k}=`)); return a ? (a.includes('=') ? a.slice(a.indexOf('=') + 1) : true) : d; };
const name = String(opt('name', 'OpenSpec Dashboard'));
const port = Number(opt('port', serverArgs.find((a) => a.startsWith('--port='))?.slice(7) ?? 4590));
const slug = name.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '') || 'openspec-dashboard';
const sh = (s) => `'${String(s).replace(/'/g, `'\\''`)}'`; // a word for the shell, quoted
const pidFile = path.join(STATE_DIR, `launcher-${port}.pid`);
// Node.js by a path that survives updates (e.g. Homebrew's /opt/homebrew/bin/node rather than its versioned Cellar path)
const nodeBin = (process.env.PATH ?? '').split(path.delimiter).map((d) => path.join(d, 'node')).find((f) => { try { return fs.realpathSync(f) === fs.realpathSync(process.execPath); } catch { return false; } }) ?? process.execPath;

function launcherScript({ open }) {
  const args = [...serverArgs.filter((a) => !a.startsWith('--port=') && a !== '--no-open'), `--port=${port}`, '--no-open'];
  const log = process.platform === 'darwin' ? path.join(os.homedir(), 'Library', 'Logs', `${slug}.log`) : path.join(STATE_DIR, `${slug}.log`);
  return `#!/bin/bash
# Generated by ${path.join(HERE, 'launcher.mjs')} — starts the OpenSpec dashboard if needed, then opens it.
export PATH=${sh(process.env.PATH ?? '/usr/bin:/bin')}
URL="http://localhost:${port}/"
up() { curl -s -o /dev/null --max-time 1 "\${URL}api/projects"; }
if ! up; then
  mkdir -p ${sh(STATE_DIR)}
  cd ${sh(process.cwd())} || exit 1
  nohup ${sh(nodeBin)} ${sh(path.join(HERE, 'server.mjs'))} ${args.map(sh).join(' ')} >> ${sh(log)} 2>&1 &
  echo $! > ${sh(pidFile)}
  disown
  for i in $(seq 1 80); do sleep 0.25; up && break; done
fi
${open}
`;
}
// how the page is opened: the default browser, or (--app-window) a window of its own in a Chromium browser
function openLine() {
  if (process.platform === 'darwin') {
    if (opt('app-window')) {
      const app = ['Google Chrome', 'Microsoft Edge', 'Brave Browser', 'Chromium'].find((a) => fs.existsSync(`/Applications/${a}.app`));
      if (app) return `open -na ${sh(app)} --args --app="$URL"`;
      console.log('No Chrome, Edge or Brave found: the launcher opens a browser tab.');
    }
    return 'open "$URL"';
  }
  if (opt('app-window')) {
    const bin = ['google-chrome', 'chromium', 'chromium-browser', 'microsoft-edge', 'brave-browser'].find((b) => { try { execFileSync('which', [b], { stdio: 'ignore' }); return true; } catch { return false; } });
    if (bin) return `${bin} --app="$URL" >/dev/null 2>&1 &`;
  }
  return 'xdg-open "$URL" >/dev/null 2>&1';
}

function installMac() {
  const app = path.join(os.homedir(), 'Applications', `${name}.app`);
  const contents = path.join(app, 'Contents');
  fs.rmSync(app, { recursive: true, force: true });
  fs.mkdirSync(path.join(contents, 'MacOS'), { recursive: true });
  fs.mkdirSync(path.join(contents, 'Resources'), { recursive: true });
  fs.writeFileSync(path.join(contents, 'Info.plist'), `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0"><dict>
  <key>CFBundleName</key><string>${name.replace(/[<&]/g, '')}</string>
  <key>CFBundleDisplayName</key><string>${name.replace(/[<&]/g, '')}</string>
  <key>CFBundleIdentifier</key><string>local.openspec-dashboard.${slug}</string>
  <key>CFBundleExecutable</key><string>launcher</string>
  <key>CFBundleIconFile</key><string>AppIcon</string>
  <key>CFBundlePackageType</key><string>APPL</string>
  <key>CFBundleShortVersionString</key><string>1.0</string>
  <key>LSUIElement</key><true/>
</dict></plist>
`);
  const exe = path.join(contents, 'MacOS', 'launcher');
  fs.writeFileSync(exe, launcherScript({ open: openLine() }), { mode: 0o755 });
  // the icon: logo-1024.png in all the sizes macOS wants, made into an .icns with the system's own tools
  try {
    const set = path.join(os.tmpdir(), `${slug}-${process.pid}.iconset`);
    fs.mkdirSync(set, { recursive: true });
    for (const s of [16, 32, 128, 256, 512]) {
      execFileSync('sips', ['-z', String(s), String(s), path.join(HERE, 'logo-1024.png'), '--out', path.join(set, `icon_${s}x${s}.png`)], { stdio: 'ignore' });
      execFileSync('sips', ['-z', String(s * 2), String(s * 2), path.join(HERE, 'logo-1024.png'), '--out', path.join(set, `icon_${s}x${s}@2x.png`)], { stdio: 'ignore' });
    }
    execFileSync('iconutil', ['-c', 'icns', set, '-o', path.join(contents, 'Resources', 'AppIcon.icns')], { stdio: 'ignore' });
    fs.rmSync(set, { recursive: true, force: true });
  } catch (e) { console.log(`The icon could not be made (${e.message.split('\n')[0]}); the app works without it.`); }
  try { execFileSync('touch', [app]); } catch { /* Finder refreshes the icon anyway */ }
  console.log(`Installed ${app}\nStart it from Launchpad, Spotlight or the Applications folder; drag it to the Dock to keep it there.`);
}
function installLinux() {
  const dir = path.join(os.homedir(), '.local', 'share', 'openspec-dashboard');
  fs.mkdirSync(dir, { recursive: true });
  const exe = path.join(dir, `${slug}.sh`);
  fs.writeFileSync(exe, launcherScript({ open: openLine() }), { mode: 0o755 });
  const apps = path.join(os.homedir(), '.local', 'share', 'applications');
  fs.mkdirSync(apps, { recursive: true });
  const entry = path.join(apps, `${slug}.desktop`);
  fs.writeFileSync(entry, `[Desktop Entry]\nType=Application\nName=${name}\nComment=OpenSpec progress dashboard\nExec=${exe}\nIcon=${path.join(HERE, 'logo.svg')}\nTerminal=false\nCategories=Development;\n`);
  console.log(`Installed ${entry} (starts ${exe}); it shows up in the application menu.`);
}
function uninstall() {
  const targets = process.platform === 'darwin' ? [path.join(os.homedir(), 'Applications', `${name}.app`)]
    : [path.join(os.homedir(), '.local', 'share', 'applications', `${slug}.desktop`), path.join(os.homedir(), '.local', 'share', 'openspec-dashboard', `${slug}.sh`)];
  for (const t of targets) if (fs.existsSync(t)) { fs.rmSync(t, { recursive: true, force: true }); console.log(`Removed ${t}`); }
}
function stop() {
  let pid = 0;
  try { pid = Number(fs.readFileSync(pidFile, 'utf8').trim()); } catch { /* none */ }
  if (!pid) return console.log(`No dashboard started by the launcher on port ${port}.`);
  try { process.kill(pid, 'SIGTERM'); console.log(`Stopped the dashboard on port ${port} (pid ${pid}).`); } catch { console.log('It was not running any more.'); }
  fs.rmSync(pidFile, { force: true });
}

if (cmd === 'install') {
  if (process.platform === 'darwin') installMac();
  else if (process.platform === 'linux') installLinux();
  else { console.error('The launcher supports macOS and Linux; on Windows, start server.mjs from a shortcut.'); process.exit(1); }
} else if (cmd === 'uninstall') uninstall();
else if (cmd === 'stop') stop();
else {
  console.log(fs.readFileSync(fileURLToPath(import.meta.url), 'utf8').split('\n').slice(1, 12).map((l) => l.replace(/^\/\/ ?/, '')).join('\n'));
  process.exit(cmd ? 1 : 0);
}
