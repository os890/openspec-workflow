#!/usr/bin/env node
// An app launcher for the OpenSpec dashboard: one click starts the dashboard (if it is not running yet) and opens it
// in the browser. macOS: an app in ~/Applications (Launchpad, Spotlight, Dock); Linux: a desktop entry.
//
//   node launcher.mjs install [--name="OpenSpec Dashboard"] [--port=4590] [--tab] [--service] [--no-app] -- <server options>
//   node launcher.mjs uninstall [--name="OpenSpec Dashboard"]
//   node launcher.mjs stop [--port=4590]          stops a dashboard the launcher started
//
// Everything after "--" is passed to server.mjs, e.g. `-- --agent --scan=~/code` or `-- --agent --project=~/code/app`.
// The launcher remembers the folder it was installed from (relative paths in the options start there), this Node.js
// and the PATH, since an app started from the Dock gets neither a shell nor its PATH. The dashboard opens in a window
// of its own, like an app (Chrome, Edge, Brave or Chromium in app mode: no tabs, no address bar); --tab opens it in
// a tab of the default browser instead (also when none of those browsers is installed). Once the page is installed as
// a web app (Chrome: Install in the address bar; it gets its own icon in the Dock), the launcher opens that app.
// --service keeps the dashboard running from login on (macOS: a LaunchAgent; Linux: a systemd user service), so the
// installed web app, pinned to the Dock, always finds it; `uninstall` removes the service too. With the web app
// installed, the launcher app itself is not needed any more: --no-app (with --service) installs only the service.
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const STATE_DIR = path.join(process.env.XDG_STATE_HOME || path.join(os.homedir(), '.local', 'state'), 'openspec-dashboard');
const argv = process.argv.slice(2);
const cut = argv.indexOf('--');
const own = cut < 0 ? argv : argv.slice(0, cut), serverArgs = cut < 0 ? [] : argv.slice(cut + 1);
const cmd = own[0];
const opt = (k, d) => { const a = own.find((x) => x === `--${k}` || x.startsWith(`--${k}=`)); return a ? (a.includes('=') ? a.slice(a.indexOf('=') + 1) : true) : d; };
const name = String(opt('name', 'OpenSpec Dashboard'));
const port = Number(opt('port', serverArgs.find((a) => a.startsWith('--port='))?.slice(7) ?? 4590));
const slug = name.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '') || 'openspec-dashboard';
const sh = (s) => `'${String(s).replace(/'/g, `'\\''`)}'`; // a word for the shell, quoted
const pidFile = path.join(STATE_DIR, `launcher-${port}.pid`);
// Node.js by a path that survives updates (e.g. Homebrew's /opt/homebrew/bin/node rather than its versioned Cellar path)
const nodeBin = (process.env.PATH ?? '').split(path.delimiter).map((d) => path.join(d, 'node')).find((f) => { try { return fs.realpathSync(f) === fs.realpathSync(process.execPath); } catch { return false; } }) ?? process.execPath;

const args = [...serverArgs.filter((a) => !a.startsWith('--port=') && a !== '--no-open'), `--port=${port}`, '--no-open'];
const log = process.platform === 'darwin' ? path.join(os.homedir(), 'Library', 'Logs', `${slug}.log`) : path.join(STATE_DIR, `${slug}.log`);
function launcherScript({ open }) {
  return `#!/bin/bash
# Generated by ${path.join(HERE, 'launcher.mjs')} — starts the OpenSpec dashboard if needed, then opens it.
export PATH=${sh(process.env.PATH ?? '/usr/bin:/bin')}
URL="http://localhost:${port}/"
up() { curl -s -o /dev/null --max-time 1 "\${URL}api/projects"; }
if ! up; then
  mkdir -p ${sh(STATE_DIR)}
  cd ${sh(process.cwd())} || exit 1
  nohup ${sh(nodeBin)} ${sh(path.join(HERE, 'server.mjs'))} ${args.map(sh).join(' ')} >> ${sh(log)} 2>&1 &
  echo $! > ${sh(pidFile)}
  disown
  for i in $(seq 1 80); do sleep 0.25; up && break; done
fi
${open}
`;
}
// how the page is opened: a window of its own in a Chromium browser (app mode), or (--tab, or none found) a tab of
// the default browser
function openLine() {
  const appWindow = !opt('tab');
  if (process.platform === 'darwin') {
    if (appWindow) {
      const app = ['Google Chrome', 'Microsoft Edge', 'Brave Browser', 'Chromium'].find((a) => fs.existsSync(`/Applications/${a}.app`) || fs.existsSync(path.join(os.homedir(), 'Applications', `${a}.app`)));
      // the page installed as a web app (Chrome/Edge/Brave put it into ~/Applications/<browser> Apps.localized/)
      const webApp = `WEBAPP=$(ls -d "$HOME/Applications/"*" Apps.localized/OpenSpec Dashboard.app" 2>/dev/null | head -1)`;
      if (app) { console.log(`It opens in a window of its own (${app}, app mode; the installed web app once there is one).`); return `${webApp}\nif [ -n "$WEBAPP" ]; then open "$WEBAPP"; else open -na ${sh(app)} --args --app="$URL"; fi`; }
      console.log('No Chrome, Edge, Brave or Chromium found: the launcher opens a browser tab.');
    }
    return 'open "$URL"';
  }
  if (appWindow) {
    const bin = ['google-chrome', 'chromium', 'chromium-browser', 'microsoft-edge', 'brave-browser'].find((b) => { try { execFileSync('which', [b], { stdio: 'ignore' }); return true; } catch { return false; } });
    if (bin) return `${bin} --app="$URL" >/dev/null 2>&1 &`;
  }
  return 'xdg-open "$URL" >/dev/null 2>&1';
}

function installMac() {
  const app = path.join(os.homedir(), 'Applications', `${name}.app`);
  const contents = path.join(app, 'Contents');
  fs.rmSync(app, { recursive: true, force: true });
  fs.mkdirSync(path.join(contents, 'MacOS'), { recursive: true });
  fs.mkdirSync(path.join(contents, 'Resources'), { recursive: true });
  fs.writeFileSync(path.join(contents, 'Info.plist'), `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0"><dict>
  <key>CFBundleName</key><string>${name.replace(/[<&]/g, '')}</string>
  <key>CFBundleDisplayName</key><string>${name.replace(/[<&]/g, '')}</string>
  <key>CFBundleIdentifier</key><string>${bundleId}</string>
  <key>CFBundleExecutable</key><string>launcher</string>
  <key>CFBundleIconFile</key><string>AppIcon</string>
  <key>CFBundlePackageType</key><string>APPL</string>
  <key>CFBundleShortVersionString</key><string>1.0</string>
  <key>LSUIElement</key><true/>
</dict></plist>
`);
  const exe = path.join(contents, 'MacOS', 'launcher');
  fs.writeFileSync(exe, launcherScript({ open: openLine() }), { mode: 0o755 });
  // the icon: logo-1024.png in all the sizes macOS wants, made into an .icns with the system's own tools
  try {
    const set = path.join(os.tmpdir(), `${slug}-${process.pid}.iconset`);
    fs.mkdirSync(set, { recursive: true });
    for (const s of [16, 32, 128, 256, 512]) {
      execFileSync('sips', ['-z', String(s), String(s), path.join(HERE, 'logo-1024.png'), '--out', path.join(set, `icon_${s}x${s}.png`)], { stdio: 'ignore' });
      execFileSync('sips', ['-z', String(s * 2), String(s * 2), path.join(HERE, 'logo-1024.png'), '--out', path.join(set, `icon_${s}x${s}@2x.png`)], { stdio: 'ignore' });
    }
    execFileSync('iconutil', ['-c', 'icns', set, '-o', path.join(contents, 'Resources', 'AppIcon.icns')], { stdio: 'ignore' });
    fs.rmSync(set, { recursive: true, force: true });
  } catch (e) { console.log(`The icon could not be made (${e.message.split('\n')[0]}); the app works without it.`); }
  try { execFileSync('touch', [app]); } catch { /* Finder refreshes the icon anyway */ }
  console.log(`Installed ${app}\nStart it from Launchpad, Spotlight or the Applications folder; drag it to the Dock to keep it there.`);
}
function installLinux() {
  const dir = path.join(os.homedir(), '.local', 'share', 'openspec-dashboard');
  fs.mkdirSync(dir, { recursive: true });
  const exe = path.join(dir, `${slug}.sh`);
  fs.writeFileSync(exe, launcherScript({ open: openLine() }), { mode: 0o755 });
  const apps = path.join(os.homedir(), '.local', 'share', 'applications');
  fs.mkdirSync(apps, { recursive: true });
  const entry = path.join(apps, `${slug}.desktop`);
  fs.writeFileSync(entry, `[Desktop Entry]\nType=Application\nName=${name}\nComment=OpenSpec progress dashboard\nExec=${exe}\nIcon=${path.join(HERE, 'logo.svg')}\nTerminal=false\nCategories=Development;\n`);
  console.log(`Installed ${entry} (starts ${exe}); it shows up in the application menu.`);
}
// --service: the dashboard runs from login on, restarted when it ends (macOS LaunchAgent, Linux systemd user unit)
const label = `local.openspec-dashboard.${slug}-${port}`;
const agentPlist = path.join(os.homedir(), 'Library', 'LaunchAgents', `${label}.plist`);
const unitFile = path.join(os.homedir(), '.config', 'systemd', 'user', `${slug}-${port}.service`);
const xml = (v) => String(v).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
// macOS names a process (Activity Monitor, the login items) after the program it runs: the service starts Node.js
// through a link named after the dashboard (in the state folder, so it works without the launcher app), and is
// associated with the launcher app when there is one
const appDir = path.join(os.homedir(), 'Applications', `${name}.app`);
const bundleId = `local.openspec-dashboard.${slug}`;
function namedNode() {
  const link = path.join(STATE_DIR, 'bin', name.replace(/\//g, '-'));
  try { fs.mkdirSync(path.dirname(link), { recursive: true }); fs.rmSync(link, { force: true }); fs.symlinkSync(nodeBin, link); return link; } catch { return nodeBin; }
}
function installService() {
  const prog = [process.platform === 'darwin' ? namedNode() : nodeBin, path.join(HERE, 'server.mjs'), ...args];
  if (process.platform === 'darwin') {
    fs.mkdirSync(path.dirname(agentPlist), { recursive: true });
    fs.writeFileSync(agentPlist, `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0"><dict>
  <key>Label</key><string>${label}</string>
${fs.existsSync(appDir) ? `  <key>AssociatedBundleIdentifiers</key><array><string>${xml(bundleId)}</string></array>\n` : ''}  <key>ProgramArguments</key><array>${prog.map((a) => `<string>${xml(a)}</string>`).join('')}</array>
  <key>WorkingDirectory</key><string>${xml(process.cwd())}</string>
  <key>EnvironmentVariables</key><dict><key>PATH</key><string>${xml(process.env.PATH ?? '/usr/bin:/bin')}</string></dict>
  <key>RunAtLoad</key><true/>
  <key>KeepAlive</key><true/>
  <key>StandardOutPath</key><string>${xml(log)}</string>
  <key>StandardErrorPath</key><string>${xml(log)}</string>
</dict></plist>
`);
    const uid = String(process.getuid());
    try { execFileSync('launchctl', ['bootout', `gui/${uid}`, agentPlist], { stdio: 'ignore' }); } catch { /* not loaded */ }
    execFileSync('launchctl', ['bootstrap', `gui/${uid}`, agentPlist]);
    console.log(`The dashboard now runs as a login service (${agentPlist}); log: ${log}`);
  } else {
    fs.mkdirSync(path.dirname(unitFile), { recursive: true });
    const q = (a) => `"${String(a).replace(/(["\\$`])/g, '\\$1')}"`;
    fs.writeFileSync(unitFile, `[Unit]\nDescription=${name}\n\n[Service]\nWorkingDirectory=${process.cwd()}\nEnvironment=${q(`PATH=${process.env.PATH ?? '/usr/bin:/bin'}`)}\nExecStart=${prog.map(q).join(' ')}\nRestart=on-failure\n\n[Install]\nWantedBy=default.target\n`);
    execFileSync('systemctl', ['--user', 'daemon-reload']);
    execFileSync('systemctl', ['--user', 'enable', '--now', path.basename(unitFile)]);
    console.log(`The dashboard now runs as a user service (${unitFile}).`);
  }
}
function removeService() {
  if (process.platform === 'darwin' && fs.existsSync(agentPlist)) {
    try { execFileSync('launchctl', ['bootout', `gui/${process.getuid()}`, agentPlist], { stdio: 'ignore' }); } catch { /* not loaded */ }
    fs.rmSync(agentPlist, { force: true }); console.log(`Removed the login service ${agentPlist}`);
  }
  if (process.platform === 'linux' && fs.existsSync(unitFile)) {
    try { execFileSync('systemctl', ['--user', 'disable', '--now', path.basename(unitFile)], { stdio: 'ignore' }); } catch { /* not there */ }
    fs.rmSync(unitFile, { force: true }); console.log(`Removed the user service ${unitFile}`);
  }
}
function uninstall() {
  removeService();
  const targets = process.platform === 'darwin' ? [path.join(os.homedir(), 'Applications', `${name}.app`)]
    : [path.join(os.homedir(), '.local', 'share', 'applications', `${slug}.desktop`), path.join(os.homedir(), '.local', 'share', 'openspec-dashboard', `${slug}.sh`)];
  for (const t of targets) if (fs.existsSync(t)) { fs.rmSync(t, { recursive: true, force: true }); console.log(`Removed ${t}`); }
}
function stop() {
  if (fs.existsSync(agentPlist) || fs.existsSync(unitFile)) {
    console.log('The dashboard runs as a service, which starts it again; `uninstall` removes the service.');
  }
  let pid = 0;
  try { pid = Number(fs.readFileSync(pidFile, 'utf8').trim()); } catch { /* none */ }
  if (!pid) return console.log(`No dashboard started by the launcher on port ${port}.`);
  try { process.kill(pid, 'SIGTERM'); console.log(`Stopped the dashboard on port ${port} (pid ${pid}).`); } catch { console.log('It was not running any more.'); }
  fs.rmSync(pidFile, { force: true });
}

if (cmd === 'install') {
  if (opt('no-app') && !opt('service')) { console.error('--no-app only makes sense with --service.'); process.exit(1); }
  if (opt('no-app')) {
    // only the service; a launcher app installed earlier goes (the web app opens the dashboard)
    if (process.platform === 'darwin' && fs.existsSync(appDir)) { fs.rmSync(appDir, { recursive: true, force: true }); console.log(`Removed the launcher app ${appDir}`); }
  } else if (process.platform === 'darwin') installMac();
  else if (process.platform === 'linux') installLinux();
  if (opt('service') && ['darwin', 'linux'].includes(process.platform)) installService();
  else { console.error('The launcher supports macOS and Linux; on Windows, start server.mjs from a shortcut.'); process.exit(1); }
} else if (cmd === 'uninstall') uninstall();
else if (cmd === 'stop') stop();
else {
  console.log(fs.readFileSync(fileURLToPath(import.meta.url), 'utf8').split('\n').slice(1, 12).map((l) => l.replace(/^\/\/ ?/, '')).join('\n'));
  process.exit(cmd ? 1 : 0);
}
